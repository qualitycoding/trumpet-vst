#!/usr/bin/env python3
"""Print the C++ fingering table from the frozen fixture (S-003). Usage: gen_fingering_table.py [fixture] > table.inc"""
import pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
fixture = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "tests/fixtures/trumpet_fingerings.txt"
VALVES = {"0": 0, "1": 1, "2": 2, "12": 3, "3": 4, "13": 5, "23": 6, "123": 7}
TRIGGER = {"-": "Trigger::None", "1": "Trigger::First", "3": "Trigger::Third"}
print(f"// Generated by tools/gen_fingering_table.py from {fixture.name}; do not edit.")
for line in fixture.read_text().splitlines():
    line = line.split("#", 1)[0].strip()
    if not line:
        continue
    written, valves, partial, trigger, kind = line.split()
    assert partial.startswith("p") and kind in ("std", "alt")
    print(f"    {{{int(written)}, {VALVES[valves]}, {int(partial[1:])}, {TRIGGER[trigger]}, {'true' if kind == 'alt' else 'false'}}},")
